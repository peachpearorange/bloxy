impl Glyph {
  pub const ALL: [Glyph; Glyph::VARIANTS.len()] = *Glyph::VARIANTS.first_chunk().unwrap();

  pub fn art(self) -> &'static Art {
    match self {
      Glyph::Star => &STAR,
      Glyph::Boot => &BOOT,
      Glyph::Wing => &WING,
      Glyph::Wave => &WAVE,
      Glyph::Heart => &HEART,
      Glyph::Shield => &SHIELD,
      Glyph::Mend => &MEND,
      Glyph::Fist => &FIST,
      Glyph::Pick => &PICK,
      Glyph::Gem => &GEM,
      Glyph::Rune => &RUNE,
      Glyph::Flame => &FLAME,
      Glyph::Snowflake => &SNOWFLAKE,
      Glyph::Missile => &MISSILE,
      Glyph::Hand => &HAND,
      Glyph::Hourglass => &HOURGLASS,
      Glyph::Stone => &STONE,
      Glyph::Feather => &FEATHER,
      Glyph::Sun => &SUN,
      Glyph::Thunder => &THUNDER,
      Glyph::Drop => &DROP,
      Glyph::Broken => &BROKEN,
      Glyph::Eye => &EYE,
      Glyph::Burst => &BURST,
      Glyph::Storm => &STORM,
      Glyph::Skull => &SKULL,
      Glyph::Ghost => &GHOST,
      Glyph::Cloak => &CLOAK,
      Glyph::Axe => &AXE,
      Glyph::Sword => &SWORD,
      Glyph::Dash => &DASH
    }
  }

  pub fn shade(self, x: u32, y: u32) -> Option<usize> {
    self.art()[y as usize]
      .as_bytes()
      .get(x as usize)
      .and_then(|&mark| (mark as char).to_digit(10))
      .map(|shade| shade as usize)
  }

  pub fn index(self) -> usize {
    Glyph::ALL.iter().position(|&glyph| glyph == self).unwrap_or(0)
  }
}

pub const CELL: u32 = 16;

pub fn sheet(paints: &[(Glyph, Shades)]) -> Image {
  let wide = CELL * paints.len() as u32;
  let mut image = Image::new(
    Extent3d { width: wide, height: CELL, depth_or_array_layers: 1 },
    TextureDimension::D2,
    (0..wide * CELL)
      .flat_map(|index| {
        let (x, y) = (index % wide, index / wide);
        let (glyph, shades) = paints[(x / CELL) as usize];
        glyph.shade(x % CELL, y).map_or([0, 0, 0, 0], |shade| {
          let [r, g, b] = shades[shade].map(|channel| (channel * 255.0) as u8);
          [r, g, b, 255]
        })
      })
      .collect(),
    TextureFormat::Rgba8UnormSrgb,
    RenderAssetUsages::default()
  );
  image.sampler = ImageSampler::nearest();
  image
}

pub fn cell(index: usize) -> Rect {
  let left = (index as u32 * CELL) as f32;
  Rect::new(left, 0.0, left + CELL as f32, CELL as f32)
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn glyphs_are_square() {
    for glyph in Glyph::ALL.into_iter() {
      for row in glyph.art().iter() {
        assert_eq!(row.len(), 16, "{glyph:?}: {row:?}")
      }
    }
  }

  #[test]
  #[ignore]
  fn glyph_sheet() {
    let zoom = 8;
    let (wide, tall) = (Glyph::ALL.len() as u32 * 18 * zoom, 18 * zoom);
    let image: Vec<u8> = (0..wide * tall)
      .flat_map(|index| {
        let (x, y) = (index % wide / zoom, index / wide / zoom);
        let (cell, x, y) = (x / 18, x % 18, y);
        match (x.checked_sub(1), y.checked_sub(1)) {
          (Some(x), Some(y)) if x < 16 && y < 16 => {
            Glyph::ALL[cell as usize].shade(x, y).map_or([40, 44, 50], |shade| {
              [[0.16, 0.13, 0.05], [0.56, 0.43, 0.19], [0.9, 0.7, 0.3], [1.0, 0.9, 0.6]]
                [shade]
                .map(|channel: f32| (channel * 255.0) as u8)
            })
          }
          _ => [20, 22, 26]
        }
      })
      .collect();
    let mut file = format!("P6 {wide} {tall} 255\n").into_bytes();
    file.extend(image);
    std::fs::write("screenshots/glyphs.ppm", file).unwrap()
  }
}
